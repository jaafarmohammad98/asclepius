import { createHash } from "node:crypto";
import { defineConfig, type Plugin } from "vite";

/**
 * Emit sw.js: a service worker that stores every built file on first load and
 * serves them from that store, so the page opens and works with no connection.
 * The cache name is a hash of the file list, so a new build replaces the old copy.
 */
function offline(): Plugin {
  return {
    name: "offline-service-worker",
    apply: "build",
    generateBundle(_, bundle) {
      const files = ["./", "./index.html", ...Object.keys(bundle).filter((f) => f !== "index.html").map((f) => `./${f}`)];
      const version = createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: `// generated by web/vite.config.ts
const CACHE = "dutch-extractor-${version}";
const FILES = ${JSON.stringify(files)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  if (e.request.method !== "GET") return;
  e.respondWith(
    caches.open(CACHE).then((c) =>
      c.match(e.request, { ignoreSearch: true, ignoreVary: true }).then((hit) => hit || fetch(e.request)),
    ),
  );
});
`,
      });
    },
  };
}

// Builds the browser page into extractor/dist as a static folder. Relative
// asset paths (base "./") let the folder be hosted under any path.
export default defineConfig({
  root: import.meta.dirname,
  base: "./",
  build: {
    outDir: "../dist",
    emptyOutDir: true,
    target: "es2022",
  },
  worker: { format: "es" },
  plugins: [offline()],
});
